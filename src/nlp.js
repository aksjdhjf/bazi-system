// 规范化：去掉常见行政后缀，便于匹配「成都市」「北京朝阳区」等写法
function norm(text) {
  return String(text || '').replace(/(省|市|县|区|自治州|自治区|特别行政区|维吾尔|壮族|回族|藏族|盟|地区|新区|镇|乡)/g, '').trim();
}

function matchCity(text) {
  const t = norm(text);
  if (!t) return null;
  if (ALIAS[t]) return { city: ALIAS[t], longitude: CITIES[ALIAS[t]], approx: false };
  // 最长匹配优先：文本包含某城市名，或城市名是文本的子串（双向，仅当 t 长度≥2 防误匹配）
  let best = null;
  for (const c of Object.keys(CITIES)) {
    if (t.includes(c) || (t.length >= 2 && c.includes(t))) {
      if (!best || c.length > best.city.length) best = { city: c, longitude: CITIES[c], approx: false };
    }
  }
  return best;
}

function parseTime(text) {
  let hour = null, minute = 0;
  let m = text.match(/(\d{1,2})[:：](\d{2})/);
  if (m) { hour = +m[1]; minute = +m[2]; }
  else {
    m = text.match(/(\d{1,2})\s*点\s*(半|一刻|三刻|[\u4e00-\u9fa5]?刻)?/);
    if (!m) m = text.match(/(\d{1,2})\s*时/);
    if (m) {
      hour = +m[1];
      const tail = m[2] || '';
      if (tail.includes('半')) minute = 30;
      else if (tail.includes('三刻')) minute = 45;
      else if (tail.includes('一刻')) minute = 15;
    }
  }
  if (hour === null) return null;
  if (/(下午|晚上|夜里|夜晚|晚间)/.test(text)) { if (hour < 12) hour += 12; }
  else if (/(上午|早上|早晨|凌晨|清晨)/.test(text)) { if (hour === 12) hour = 0; }
  else if (/(中午|正午)/.test(text)) { hour = 12; }
  if (hour > 23) hour = 23;
  return { hour, minute };
}

function parseDate(text) {
  let m = text.match(/(\d{4})\s*年\s*(\d{1,2})\s*月\s*(\d{1,2})\s*日?/);
  if (!m) m = text.match(/(\d{4})[-/](\d{1,2})[-/](\d{1,2})/);
  if (!m) m = text.match(/(\d{2})\s*年\s*(\d{1,2})\s*月\s*(\d{1,2})\s*日?/);
  if (!m) return null;
  let y = +m[1];
  if (y < 100) y = y < 30 ? 2000 + y : 1900 + y;
  return { year: y, month: +m[2], day: +m[3] };
}

function parseGender(text) {
  if (/(男|先生|男士|兄弟|公子)/.test(text)) return '男';
  if (/(女|女士|姑娘|妹|姐|小姐)/.test(text)) return '女';
  return null;
}

// 合并已知字段 + 文本抽取，返回结构化字段与缺失项
function extract(text, known = {}) {
  const merged = { ...known };
  if (text && typeof text === 'string') {
    const d = parseDate(text);
    if (d) Object.assign(merged, d);
    const t = parseTime(text);
    if (t) { merged.hour = t.hour; merged.minute = t.minute; }
    const g = parseGender(text);
    if (g) merged.gender = g;
    const c = matchCity(text);
    if (c) { merged.city = c.city; merged.longitude = c.longitude; merged.longitude_approx = false; }
  }
  // 表单传入的城市也尝试匹配（兼容带市/县后缀等写法）
  if (merged.city && (merged.longitude === undefined || merged.longitude === null)) {
    const c = matchCity(merged.city);
    if (c) { merged.city = c.city; merged.longitude = c.longitude; merged.longitude_approx = false; }
    else { merged.longitude = 120; merged.longitude_approx = true; } // 未知地点：按北京时间近似
  }
  // 用户手动填了经度则优先（精确），标记为精确
  if (merged.longitude !== undefined && merged.longitude !== null && !merged.longitude_approx) {
    // 已匹配城市，精确
  } else if (merged.longitude === undefined || merged.longitude === null) {
    merged.longitude = 120; merged.longitude_approx = true;
  }
  // 校验（出生地不再缺失：总能用近似经度排盘，不再卡追问）
  const missing = [];
  if (!merged.year || !merged.month || !merged.day) missing.push('birth_date');
  if (merged.hour === undefined || merged.hour === null) missing.push('birth_time');
  if (!merged.gender) missing.push('gender');
  const complete = missing.length === 0;
  return { fields: merged, missing, complete };
}

